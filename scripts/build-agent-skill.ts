/**
 * Builds the published Agent Skill from what the MCP server lists:
 *   skills/gridfinity-layout-tool/references/tools.md   the tool reference
 *   apps/docs/public/gridfinity-layout-tool-skill.zip   the folder, for upload
 *
 * Usage: `pnpm run build:agent-skill`, after any change to a tool or the Skill.
 * `build-agent-skill.test.ts` fails when either output is stale.
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { InMemoryTransport } from '@modelcontextprotocol/sdk/inMemory.js';
import type { Tool } from '@modelcontextprotocol/sdk/types.js';
import { zipSync } from 'fflate';
import type { Zippable } from 'fflate';
import * as prettier from 'prettier';
import { createMcpServer } from '../api/lib/mcp/server.js';

// fflate writes zip times from local clock fields, so the zip bytes would
// otherwise depend on the machine's time zone.
process.env.TZ = 'UTC';

const ROOT = path.resolve(import.meta.dirname, '..');
export const SKILL_NAME = 'gridfinity-layout-tool';
export const SKILL_DIR = path.join(ROOT, 'skills', SKILL_NAME);
export const REFERENCE_FILE = path.join(SKILL_DIR, 'references', 'tools.md');
export const ZIP_FILE = path.join(ROOT, 'apps', 'docs', 'public', `${SKILL_NAME}-skill.zip`);
const ZIP_TIME = new Date('2026-01-01T00:00:00Z');

interface SchemaNode {
  readonly type?: string | readonly string[];
  readonly description?: string;
  readonly properties?: Readonly<Record<string, SchemaNode>>;
  readonly required?: readonly string[];
  readonly items?: SchemaNode;
  readonly enum?: readonly unknown[];
  readonly minimum?: number;
  readonly maximum?: number;
  readonly exclusiveMinimum?: number;
  readonly minItems?: number;
  readonly maxItems?: number;
  readonly minLength?: number;
  readonly maxLength?: number;
}

function typeName(node: SchemaNode): string {
  if (node.type === 'array') return `${node.items ? typeName(node.items) : 'value'} list`;
  if (Array.isArray(node.type)) return node.type.join(' or ');
  return typeof node.type === 'string' ? node.type : 'value';
}

function limits(node: SchemaNode): string[] {
  const notes: string[] = [];
  if (node.enum) notes.push(`One of ${node.enum.map((v) => `\`${String(v)}\``).join(', ')}.`);
  if (node.exclusiveMinimum !== undefined) notes.push(`Over ${node.exclusiveMinimum}.`);
  if (node.minimum !== undefined && node.maximum !== undefined)
    notes.push(`${node.minimum} to ${node.maximum}.`);
  else if (node.minimum !== undefined) notes.push(`At least ${node.minimum}.`);
  else if (node.maximum !== undefined) notes.push(`At most ${node.maximum}.`);
  if (node.minItems !== undefined || node.maxItems !== undefined)
    notes.push(`${node.minItems ?? 0} to ${node.maxItems ?? 'any'} items.`);
  if (node.maxLength !== undefined) notes.push(`Up to ${node.maxLength} characters.`);
  return notes;
}

function rows(node: SchemaNode, prefix: string): string[] {
  const required = new Set(node.required ?? []);
  return Object.entries(node.properties ?? {}).flatMap(([key, child]) => {
    const name = `${prefix}${key}`;
    // A list of plain values has no rows of its own, so its item limits go here.
    const itemLimits =
      child.type === 'array' && child.items && !child.items.properties
        ? limits(child.items).map(
            (note) => `Each item: ${note.charAt(0).toLowerCase()}${note.slice(1)}`
          )
        : [];
    const notes = [child.description, ...limits(child), ...itemLimits].filter(Boolean).join(' ');
    const row = `| \`${name}\` | ${typeName(child)} | ${required.has(key) ? 'yes' : 'no'} | ${notes.replaceAll('|', '\\|')} |`;
    const nested = child.type === 'array' && child.items ? child.items : child;
    const nestedPrefix = child.type === 'array' ? `${name}[].` : `${name}.`;
    return [row, ...rows(nested, nestedPrefix)];
  });
}

export function renderToolReference(tools: readonly Tool[]): string {
  const sections = [...tools]
    .sort((a, b) => a.name.localeCompare(b.name))
    .map((tool) => {
      const input = tool.inputSchema as SchemaNode;
      return [
        `## \`${tool.name}\`: ${tool.title ?? tool.name}`,
        '',
        tool.description ?? '',
        '',
        '| Input | Type | Required | Notes |',
        '| --- | --- | --- | --- |',
        ...rows(input, ''),
      ].join('\n');
    });
  return [
    '<!-- Generated by scripts/build-agent-skill.ts from the MCP server. Do not edit. -->',
    '',
    '# Tool reference',
    '',
    'Every tool of the Gridfinity Layout Tool MCP server, with its inputs. All the tools only compute from their input: they read and change nothing.',
    '',
    ...sections.flatMap((section) => [section, '']),
  ].join('\n');
}

export async function listServerTools(): Promise<Tool[]> {
  const server = createMcpServer('https://gridfinitylayouttool.com', 'skill');
  const [clientSide, serverSide] = InMemoryTransport.createLinkedPair();
  await server.connect(serverSide);
  const client = new Client({ name: 'build-agent-skill', version: '1' });
  await client.connect(clientSide);
  const { tools } = await client.listTools();
  await client.close();
  return tools;
}

export async function formatMarkdown(text: string, file: string): Promise<string> {
  const config = (await prettier.resolveConfig(file)) ?? {};
  return prettier.format(text, { ...config, filepath: file });
}

/** Each file of the Skill folder by its path inside the zip, such as `gridfinity-layout-tool/SKILL.md`. */
export function skillFiles(): Map<string, Uint8Array> {
  const files = new Map<string, Uint8Array>();
  const walk = (dir: string): void => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) walk(full);
      else
        files.set(
          path.posix.join(SKILL_NAME, path.relative(SKILL_DIR, full).split(path.sep).join('/')),
          new Uint8Array(readFileSync(full))
        );
    }
  };
  walk(SKILL_DIR);
  return new Map([...files].sort(([a], [b]) => a.localeCompare(b)));
}

export function zipSkill(files: ReadonlyMap<string, Uint8Array>): Uint8Array {
  const entries: Zippable = {};
  for (const [name, bytes] of files) entries[name] = [bytes, { mtime: ZIP_TIME }];
  return zipSync(entries, { level: 9 });
}

async function main(): Promise<void> {
  const reference = await formatMarkdown(
    renderToolReference(await listServerTools()),
    REFERENCE_FILE
  );
  mkdirSync(path.dirname(REFERENCE_FILE), { recursive: true });
  writeFileSync(REFERENCE_FILE, reference);
  const files = skillFiles();
  writeFileSync(ZIP_FILE, zipSkill(files));
  console.log(`✓ Wrote ${path.relative(ROOT, REFERENCE_FILE)} and a zip of ${files.size} files`);
}

if (process.argv[1]?.endsWith('build-agent-skill.ts')) await main();
